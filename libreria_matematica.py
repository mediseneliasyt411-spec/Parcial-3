
# Importa el modulo math para acceder a sus funciones.
import math

print("--- LIBRERIA MATH EN PYTHON ---")

numero = 25
print("Numero:", numero)

# sqrt calcula la raiz cuadrada.
print("Raiz cuadrada:", math.sqrt(numero))

# pow calcula una potencia.
print("Potencia 5^2:", math.pow(5, 2))

# ceil redondea hacia arriba.
print("Redondeo hacia arriba:", math.ceil(4.3))

# floor redondea hacia abajo.
print("Redondeo hacia abajo:", math.floor(4.8))

# pi contiene el valor de la constante matematica pi.
print("Valor de PI:", math.pi)
